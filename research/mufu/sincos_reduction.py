"""Check the proposed SM89 SIN/COS reduction independently of the SFU evaluator.

From the repository root (GPU execution must be outside the sandbox):
  PYTHONPATH=src:. python research/mufu/sincos_reduction.py run
Replay the saved observations without a GPU or third-party dependencies:
  python research/mufu/sincos_reduction.py analyze

Inputs and observations are gzip JSON. Encodings are synthetic, generated by
Cases.probe, not compiler output. These are discovery observations, not regression
verification evidence. No approximate comparison is used for reduction checks.
"""
import argparse
from datetime import datetime, timezone
import gzip
import hashlib
import json
import math
from pathlib import Path
import struct
import subprocess

Q = 1 << 23
TURN = 1 << 25
SIGN = 1 << 31
DEFAULT = Path(__file__).with_name('sincos-reduction')


def float_value(bits):
    return struct.unpack('<f', struct.pack('<I', bits))[0]


def float_bits(value):
    return struct.unpack('<I', struct.pack('<f', value))[0]


def fraction(bits):
    """floor(abs(x)*2^25) modulo 2^25 using only the IEEE input bits."""
    exponent, mantissa = (bits >> 23) & 255, bits & (Q - 1)
    if exponent == 255:
        raise ValueError('nonfinite input')
    if exponent == 0:
        return 0
    shift = exponent - 125
    significand = Q | mantissa
    return ((significand << shift) if shift >= 0 else (significand >> -shift)) & (TURN - 1)


def reduced(op, bits, complement=True):
    phase = fraction(bits)
    if op == 'COS':
        phase = (phase + Q) & (TURN - 1)
    quadrant, offset = divmod(phase, Q)
    if quadrant & 1:
        offset = (Q - 1 if complement else Q) - offset
    negative = (quadrant >= 2) ^ (op == 'SIN' and bool(bits & SIGN))
    return offset, int(negative) << 31


def save(path, value):
    data = (json.dumps(value, separators=(',', ':'), allow_nan=False) + '\n').encode()
    path.write_bytes(gzip.compress(data, mtime=0))


def load(path):
    return json.loads(gzip.decompress(path.read_bytes()))


def inputs():
    """Deterministic vectors; convert to f32 before deriving any expected offset."""
    requests = {}

    def add(op, bits, tag):
        requests.setdefault((op, bits), set()).add(tag)

    def both(bits, tag):
        for op in ('SIN', 'COS'):
            for sign in (0, SIGN):
                add(op, bits | sign, tag)

    offsets = [i * (Q - 1) // 4095 for i in range(4096)]
    for offset in offsets:
        for quadrant in range(4):
            phase = quadrant * Q + (Q - 1 - offset if quadrant & 1 else offset)
            both(float_bits(phase / TURN), 'quadrant')

    # Start, midpoint, and final float within cells. Zero's cell also contains
    # all positive subnormals, so explicitly include the smallest normal input.
    cells = sorted(set(range(65)) | {i * (Q - 1) // 127 for i in range(128)})
    for cell in cells:
        for bits in (float_bits(cell / TURN), float_bits((cell + 0.5) / TURN),
                     float_bits((cell + 1) / TURN) - 1):
            both(bits, 'cell')

    # Both adjacent input ulps and grid steps, including translated boundaries.
    for whole in (0, 1, 2, 4, 8, 16):
        for quadrant in range(5):
            boundary = whole + quadrant / 4
            center = float_bits(boundary)
            for delta in range(-4, 5):
                if center + delta >= 0:
                    both(center + delta, 'boundary')
            for step in (-64, -16, -4, -2, -1, 0, 1, 2, 4, 16, 64):
                x = boundary + step / TURN
                if x >= 0:
                    both(float_bits(x), 'boundary')

    for offset in offsets[::32]:
        for whole in (1, 2, 4, 8, 16):
            both(float_bits(whole + offset / TURN), 'translation')

    for exponent in range(22, 128):
        center = (exponent + 127) << 23
        for delta in (-1, 0, 1):
            if center + delta < 0x7f800000:
                both(center + delta, 'large')

    for bits in (0, 1, 0x100, 0x400000, 0x7fffff, 0x800000,
                 0x32ffffff, 0x33000000, 0x3effffff, 0x3e7fffff,
                 0x7f7fffff, 0x7f800000, 0x7fc00000, 0x7f800001,
                 0x7fffffff, 0x7fa5a5a5):
        both(bits, 'special')

    # Observe the evaluator directly at each candidate offset for both models.
    # This provides a hardware baseline rather than an ideal-sine reference.
    for op, bits in list(requests):
        if bits & 0x7f800000 == 0x7f800000:
            continue
        for complement in (True, False):
            offset, _ = reduced(op, bits, complement)
            add('SIN', float_bits(offset / TURN), 'canonical')

    return [dict(op=op, input=f'{bits:08x}', tags=sorted(tags))
            for (op, bits), tags in sorted(requests.items())]


def run(directory):
    from tests.harness.case import Cases
    from tests.harness import device_cases

    directory.mkdir(parents=True, exist_ok=True)
    vectors = inputs()
    save(directory / 'inputs.json.gz', vectors)
    digest = hashlib.sha256((directory / 'inputs.json.gz').read_bytes()).hexdigest()
    metadata = dict(arch='SM89', base_commit=subprocess.check_output(
        ['git', 'rev-parse', 'HEAD'], text=True).strip(),
        script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        input_sha256=digest, started_utc=datetime.now(timezone.utc).isoformat(),
        instruction_origin='synthetic Cases.probe', batch_size=2048)
    observations = []
    for start in range(0, len(vectors), metadata['batch_size']):
        batch = vectors[start:start + metadata['batch_size']]
        cases = Cases('SM89')
        for vector in batch:
            cases.probe('mufu__RRR_RR', dict(Rd=8, Rb=2, mufuop=vector['op']),
                        dict(R2=int(vector['input'], 16)), observe=['R8'])
        result = device_cases.observe(cases, timeout=60)
        if metadata.get('device', result['device']) != result['device']:
            raise RuntimeError('GPU identity changed during experiment')
        metadata['device'] = result['device']
        observations.extend(dict(op=v['op'], input=v['input'], **row)
                            for v, row in zip(batch, result['observations'], strict=True))
        save(directory / 'observations.json.gz', dict(metadata=metadata, observations=observations))
        print(f'{len(observations)}/{len(vectors)} observations', flush=True)
        if any('error' in row for row in result['observations']):
            raise RuntimeError('GPU probe failed; partial observations saved')
    analyze(directory)


def analyze(directory):
    vectors = load(directory / 'inputs.json.gz')
    raw = load(directory / 'observations.json.gz')
    digest = hashlib.sha256((directory / 'inputs.json.gz').read_bytes()).hexdigest()
    if raw['metadata']['input_sha256'] != digest:
        raise ValueError('input artifact hash mismatch')
    rows = raw['observations']
    expected_keys = {(v['op'], v['input']) for v in vectors}
    observed_keys = {(v['op'], v['input']) for v in rows}
    if len(rows) != len(vectors) or observed_keys != expected_keys or len(observed_keys) != len(rows):
        raise ValueError('incomplete or duplicate observations')
    if any('error' in row for row in rows):
        raise ValueError('hardware errors are not model counterexamples')
    results = {(v['op'], int(v['input'], 16)): v['registers']['R8'] for v in rows}
    checks = {}

    def check(name, op, bits, got, want, **details):
        stats = checks.setdefault(name, dict(checked=0, mismatches=0, examples=[]))
        stats['checked'] += 1
        if got != want:
            stats['mismatches'] += 1
            if len(stats['examples']) < 12:
                stats['examples'].append(dict(op=op, input=f'{bits:08x}',
                    got=f'{got:08x}', want=f'{want:08x}', **details))

    cells = {}
    residuals = {op: dict(max_absolute_error=0, input=None) for op in ('SIN', 'COS')}
    for vector in vectors:
        op, bits = vector['op'], int(vector['input'], 16)
        got = results[op, bits]
        if bits & 0x7f800000 == 0x7f800000:
            check('nonfinite', op, bits, got, 0x7fffffff)
            continue
        if vector['tags'] == ['canonical']:
            continue
        for complement, name in ((True, 'complement'), (False, 'ordinary_reflection')):
            offset, sign = reduced(op, bits, complement)
            canonical = float_bits(offset / TURN)
            want = results['SIN', canonical] ^ sign
            check(f'{name}_{op}', op, bits, got, want, canonical_input=f'{canonical:08x}')
            if complement:
                for tag in vector['tags']:
                    check(f'{tag}_{op}', op, bits, got, want, canonical_input=f'{canonical:08x}')
                check('sign', op, bits, got & SIGN, sign)
                if offset == 0:
                    check('signed_zero', op, bits, got, sign)
                ideal = math.sin(2 * math.pi * offset / TURN) * (-1 if sign else 1)
                error = abs(float_value(got) - ideal)
                if error > residuals[op]['max_absolute_error']:
                    residuals[op] = dict(max_absolute_error=error, input=f'{bits:08x}')
        if 'cell' in vector['tags']:
            key = op, bool(bits & SIGN), fraction(bits)
            first_bits, first_got = cells.setdefault(key, (bits, got))
            if first_bits != bits:
                check('cell_constancy', op, bits, got, first_got, first_input=f'{first_bits:08x}')
        if bits & 0x7fffffff < 0x800000:
            check('subnormal_or_zero', op, bits, got,
                  bits & SIGN if op == 'SIN' else 0x3f800000)

    report = dict(metadata=raw['metadata'], observations=len(rows),
        selected_offsets=4096, cells=len(cells), checks=checks,
        sample_evaluator_residual=residuals,
        interpretation='Exact identities test reduction; residuals are sample bounds only. '
        'Ordinary-reflection failures are a control, not failures of the proposed model.')
    (directory / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('run', 'analyze', 'prepare'))
    parser.add_argument('--out', type=Path, default=DEFAULT)
    args = parser.parse_args()
    if args.action == 'run':
        run(args.out)
    elif args.action == 'analyze':
        analyze(args.out)
    else:
        args.out.mkdir(parents=True, exist_ok=True)
        vectors = inputs()
        save(args.out / 'inputs.json.gz', vectors)
        print(f'{len(vectors)} unique probes')


if __name__ == '__main__':
    main()
